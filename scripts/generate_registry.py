#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def parse_frontmatter(text: str) -> dict[str, str]:
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise ValueError("missing YAML frontmatter")
    data: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.startswith(" "):
            continue
        if ":" not in line:
            continue
        key, raw_val = line.split(":", 1)
        val = raw_val.strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in ('"', "'"):
            val = val[1:-1]
        data[key.strip()] = val
    return data


def render_registry(root: Path) -> str:
    skills_dir = root / "skills"
    rows: list[tuple[str, str, str]] = []
    for skill_md in sorted(skills_dir.glob("*/SKILL.md")):
        meta = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = meta.get("name", skill_md.parent.name)
        desc = meta.get("description", "").replace("|", "\\|")
        rel_path = skill_md.relative_to(root).as_posix()
        rows.append((name, desc, rel_path))

    lines = [
        "# pig-stack Skill Registry",
        "",
        "Generated by `python3 scripts/generate_registry.py`. Pass exact `Path` values to subagents; never paste summaries.",
        "",
        "| Skill | Trigger / Description | Scope | Path |",
        "| --- | --- | --- | --- |",
    ]
    for name, desc, rel_path in rows:
        lines.append(f"| `{name}` | {desc} | plugin | `{rel_path}` |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or verify .atl/skill-registry.md")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    target = root / ".atl" / "skill-registry.md"
    rendered = render_registry(root)

    if args.check:
        if not target.exists():
            print(f"MISSING: {target}", file=sys.stderr)
            return 1
        current = target.read_text(encoding="utf-8")
        if current != rendered:
            print(f"OUT OF DATE: {target}. Run python3 scripts/generate_registry.py", file=sys.stderr)
            return 1
        print(f"OK: {target} matches {len(rendered.splitlines())} lines")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text(encoding="utf-8") != rendered:
        target.write_text(rendered, encoding="utf-8")
        print(f"UPDATED: {target}")
    else:
        print(f"UNCHANGED: {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
